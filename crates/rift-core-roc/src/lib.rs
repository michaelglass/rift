/// The workspace decisions and steps (`rift_core::workspaces`) decided by the Roc core. The
/// steps answer with what a run leaves, as views of the Rust core's state.
pub mod workspaces {
    use rift_core::plain::Unasked;
    use rift_core::workspaces::plain::{
        EligibleQuestion, EmitsQuestion, PreviousQuestion, ResolveQuestion, StepQuestion,
        WorkspacesQuestion,
    };
    use rift_core::workspaces::{Activation, Ownership, Refused};

    use crate::{abi, boundary, host};

    /// What each event of a run met, and the joined workspaces it leaves: catalog,
    /// activations, owners, and each catalogued workspace's assigned windows in catalog order.
    #[derive(Debug, Clone, PartialEq)]
    pub struct JoinedView {
        pub outcomes: Vec<Result<(), Refused<u64, u64>>>,
        pub catalog: Vec<(u64, u64)>,
        pub activations: Vec<(u64, Activation<u64>)>,
        pub owners: Vec<(u64, Ownership<u64, rift_core::workspaces::plain::Claimant>)>,
        pub windows: Vec<Vec<u64>>,
    }

    /// The joined workspaces kept between events (`RocWorkspaces::view`): catalog, activations,
    /// owners, and each catalogued workspace's assigned windows in catalog order.
    #[derive(Debug, Clone, PartialEq)]
    pub struct WorkspacesView {
        pub catalog: Vec<(u64, u64)>,
        pub activations: Vec<(u64, Activation<u64>)>,
        pub owners: Vec<(u64, Ownership<u64, rift_core::workspaces::plain::Claimant>)>,
        pub windows: Vec<Vec<u64>>,
    }

    pub fn step(question: StepQuestion) -> Result<Option<u64>, Unasked> {
        let host = host();
        let question = boundary::step_question(question, &host);
        boundary::word_answer(unsafe { abi::roc_workspace_step(question) })
    }

    /// It asks for no fact.
    pub fn eligible(question: EligibleQuestion) -> bool {
        let host = host();
        let question = boundary::eligible_question(question, &host);
        unsafe { abi::roc_workspace_eligible(question) }
    }

    pub fn resolve(question: ResolveQuestion) -> Option<(u64, u64)> {
        let host = host();
        let question = boundary::resolve_question(question, &host);
        boundary::from_reached(unsafe { abi::roc_workspace_resolve(question) })
    }

    pub fn previous(question: PreviousQuestion) -> Result<Option<(u64, u64)>, Unasked> {
        let host = host();
        let question = boundary::previous_question(question, &host);
        boundary::reached_answer(unsafe { abi::roc_workspace_previous(question) })
    }

    pub fn emits_window(question: EmitsQuestion) -> Result<bool, Unasked> {
        let host = host();
        let question = boundary::emits_question(question, &host);
        boundary::verdict_answer(unsafe { abi::roc_emits_window(question) })
    }

    pub fn joined(question: WorkspacesQuestion) -> JoinedView {
        let host = host();
        let question = boundary::joined_question(question, &host);
        boundary::from_joined(unsafe { abi::roc_joined_steps(question) }, &host)
    }
}

