/// The BSP tree's operations and view, on plain keys, and the Rust tree they are held to.
pub mod bsp_tree {
    use rift_core::layout::bsp_tree::{
        Direction, Edit, Edited, Focus, Focused, InsertionPoint, Layout, Node, Participation,
        Query, Resize,
    };
    use rift_core::slot_table::{SlotKey, SlotTable, SlotsError};

    /// A layout's key: slotmap's ffi form, `version << 32 | index`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
    pub struct LayoutKey(pub u64);

    /// A node's key: slotmap's ffi form, `version << 32 | index`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
    pub struct NodeKey(pub u64);

    macro_rules! slot_key {
        ($key:ident) => {
            impl SlotKey for $key {
                fn from_parts(index: u32, version: u32) -> Self {
                    $key((u64::from(version) << 32) | u64::from(index))
                }

                fn parts(self) -> (u32, u32) { (self.0 as u32, (self.0 >> 32) as u32) }
            }
        };
    }
    slot_key!(LayoutKey);
    slot_key!(NodeKey);

    /// The Rust tree, on plain keys and windows as words.
    pub type Tree = rift_core::layout::bsp_tree::Tree<LayoutKey, NodeKey, u64>;

    /// One operation of the system (`Tree`'s methods, one for one; an app closing lists its
    /// windows, which `close_app`'s predicate tells).
    #[derive(Debug, Clone, PartialEq)]
    pub enum Event {
        CreateLayout,
        CloneLayout(LayoutKey),
        RemoveLayout(LayoutKey),
        Participation(u64, Participation),
        Insertion(InsertionPoint),
        AspectRatio(Option<f64>),
        AddWindow(LayoutKey, u64),
        RemoveWindow(u64),
        ReplaceWindow {
            from: u64,
            to: u64,
        },
        CloseApp(Vec<u64>),
        ResizeWindow(LayoutKey, u64, Resize),
        ContainsLayout(LayoutKey),
        WindowParticipates(u64),
        SelectedWindow(LayoutKey),
        WindowInDirection(LayoutKey, Direction),
        ContainsWindow(LayoutKey, u64),
        HasAnyFullscreenNode(LayoutKey),
        /// The app's windows, which `has_windows_for_app`'s predicate tells.
        HasWindowsForApp(LayoutKey, Vec<u64>),
        Windows(LayoutKey, Query<u64>),
        CanMoveWindow(LayoutKey, u64, Direction),
        WindowSlot(LayoutKey, u64),
        Focus(LayoutKey, Focus<u64>),
        Edit(LayoutKey, Edit<u64>),
    }

    /// What an operation answers.
    #[derive(Debug, Clone, PartialEq)]
    pub enum Answer {
        Layout(LayoutKey),
        Participated(bool),
        Done,
        Verdict(bool),
        Window(Option<u64>),
        Windows(Vec<u64>),
        WindowSlot(Option<Vec<usize>>),
        Focused(Focused<u64>),
        Edited(Edited<u64>),
    }

    /// `event` applied to the Rust tree, and what it answers.
    pub fn step(tree: &mut Tree, event: Event) -> Answer {
        match event {
            Event::CreateLayout => Answer::Layout(tree.create_layout()),
            Event::CloneLayout(layout) => Answer::Layout(tree.clone_layout(layout)),
            Event::RemoveLayout(layout) => {
                tree.remove_layout(layout);
                Answer::Done
            }
            Event::Participation(window, participation) => {
                Answer::Participated(tree.set_window_participation(window, participation))
            }
            Event::Insertion(insertion) => {
                tree.set_window_insertion_point(insertion);
                Answer::Done
            }
            Event::AspectRatio(ratio) => {
                tree.set_single_window_aspect_ratio(ratio);
                Answer::Done
            }
            Event::AddWindow(layout, window) => {
                tree.add_window(layout, window);
                Answer::Done
            }
            Event::RemoveWindow(window) => {
                tree.remove_window(window);
                Answer::Done
            }
            Event::ReplaceWindow { from, to } => {
                tree.replace_window(from, to);
                Answer::Done
            }
            Event::CloseApp(windows) => {
                tree.close_app(|window| windows.contains(&window));
                Answer::Done
            }
            Event::ResizeWindow(layout, window, resize) => {
                tree.resize_window(layout, window, resize);
                Answer::Done
            }
            Event::ContainsLayout(layout) => Answer::Verdict(tree.contains_layout(layout)),
            Event::WindowParticipates(window) => Answer::Verdict(tree.window_participates(window)),
            Event::SelectedWindow(layout) => Answer::Window(tree.selected_window(layout)),
            Event::WindowInDirection(layout, direction) => {
                Answer::Window(tree.window_in_direction(layout, direction))
            }
            Event::ContainsWindow(layout, window) => {
                Answer::Verdict(tree.contains_window(layout, window))
            }
            Event::HasAnyFullscreenNode(layout) => {
                Answer::Verdict(tree.has_any_fullscreen_node(layout))
            }
            Event::HasWindowsForApp(layout, windows) => Answer::Verdict(
                tree.has_windows_for_app(layout, |window| windows.contains(&window)),
            ),
            Event::Windows(layout, query) => Answer::Windows(tree.windows(layout, query)),
            Event::CanMoveWindow(layout, window, direction) => {
                Answer::Verdict(tree.can_move_window(layout, window, direction))
            }
            Event::WindowSlot(layout, window) => {
                Answer::WindowSlot(tree.window_slot(layout, window))
            }
            Event::Focus(layout, focus) => Answer::Focused(tree.focus(layout, focus)),
            Event::Edit(layout, edit) => Answer::Edited(tree.edit(layout, edit)),
        }
    }

    /// A saved slot: its value (none when vacant) and its version.
    pub type Saved<V> = (Option<V>, u32);

    /// The whole system, comparable: each table's slots and free list, the windows left out in
    /// order, the settings.
    #[derive(Debug, Clone, PartialEq)]
    pub struct TreeView {
        pub layouts: Vec<Saved<Layout<NodeKey>>>,
        pub layout_free: Vec<u32>,
        pub nodes: Vec<Saved<Node<NodeKey, u64>>>,
        pub node_free: Vec<u32>,
        pub left_out: Vec<u64>,
        pub insertion: InsertionPoint,
        pub aspect: Option<f64>,
    }

    fn saved<K: SlotKey, V: Clone>(table: &SlotTable<K, V>) -> Vec<Saved<V>> {
        table
            .saved()
            .map(|(held, version)| (held.map(|(_, value)| value.clone()), version))
            .collect()
    }

    impl TreeView {
        /// The Rust tree this view holds, its tables parsed as slotmap reads them (refused as
        /// slotmap refuses them, or when a free list is not the table's vacant slots).
        pub fn tree(&self) -> Result<Tree, SlotsError> {
            let taking = |free: &[u32]| free.iter().rev().copied().collect::<Vec<u32>>();
            Ok(Tree::from_parts(
                SlotTable::parse(self.layouts.clone())?.resumed(&taking(&self.layout_free))?,
                SlotTable::parse(self.nodes.clone())?.resumed(&taking(&self.node_free))?,
                self.left_out.iter().copied().collect(),
                self.insertion,
                self.aspect,
            ))
        }
    }

    impl From<&Tree> for TreeView {
        fn from(tree: &Tree) -> Self {
            TreeView {
                layouts: saved(tree.layouts()),
                layout_free: tree.layouts().free().to_vec(),
                nodes: saved(tree.nodes()),
                node_free: tree.nodes().free().to_vec(),
                left_out: tree.left_out().iter().copied().collect(),
                insertion: tree.insertion(),
                aspect: tree.aspect(),
            }
        }
    }
}

