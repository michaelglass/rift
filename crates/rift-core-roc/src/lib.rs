/// The Roc core. Holds the model's box, which only Roc can read or free; it is moved through
/// every step and never shared, so Roc can update it in place.
pub struct RocCore {
    model: abi::RocBox,
    host: abi::RocHost,
}

// SAFETY: the model's box is owned by this `RocCore` alone: Roc keeps no reference to it
// between steps and nothing else holds one, so moving the core to another thread (rift builds
// its reactor on one thread and runs it on another) moves the only owner. Roc's refcounts are
// not atomic, so the core is not `Sync`: one thread steps it at a time, which `&mut self` on
// `step` already requires.
unsafe impl Send for RocCore {}

impl Default for RocCore {
    fn default() -> Self {
        RocCore {
            model: unsafe { abi::roc_init() },
            host: host(),
        }
    }
}

/// What an invalidation and a revalidation found: the Rust core's named tags, as the Roc
/// boundary answers them.
pub use rift_core::lifecycle::{Invalidation, Revalidation};

/// The lifecycle of every window (`rift_core::lifecycle::Lifecycle`) kept in Roc between
/// events: each window with AX state and its presence. Stepped beside the Rust lifecycle, it
/// must make the same changes and keep the same windows.
pub struct RocLifecycle {
    windows: boundary::LifecycleBox,
    host: abi::RocHost,
}

// SAFETY: as for `RocCore`: the box has one owner, this lifecycle, and Roc keeps no reference
// to it between steps; `&mut self` on every step keeps it to one thread at a time.
unsafe impl Send for RocLifecycle {}

impl Default for RocLifecycle {
    fn default() -> Self {
        RocLifecycle {
            windows: boundary::LifecycleBox::empty(),
            host: host(),
        }
    }
}

impl RocLifecycle {
    /// As `Lifecycle::step`: the change the event makes to its window's admission, if any.
    pub fn step(
        &mut self,
        event: rift_core::lifecycle::LifecycleEvent<u64>,
    ) -> Option<rift_core::lifecycle::Change> {
        use rift_core::lifecycle::{LifecycleEvent, Reading};
        let (window, reading) = match event {
            LifecycleEvent::Live { window, facts } => (window, Reading::Live(facts)),
            LifecycleEvent::Changed { window, change } => (window, Reading::Changed(change)),
            LifecycleEvent::Gone(window) => (window, Reading::Gone),
        };
        boundary::in_place(&mut self.windows, |windows| windows.read(window, reading))
    }

    /// As `Lifecycle::invalidate`.
    pub fn invalidate(&mut self, window: u64) -> Invalidation {
        boundary::in_place(&mut self.windows, |windows| windows.invalidate(window))
    }

    /// As `Lifecycle::revalidate`.
    pub fn revalidate(&mut self, window: u64) -> Revalidation {
        boundary::in_place(&mut self.windows, |windows| windows.revalidate(window))
    }

    /// As `Lifecycle::presences`: every window with AX state and its presence, in window order.
    pub fn view(&mut self) -> Vec<(u64, rift_core::lifecycle::Presence)> {
        let host = &self.host;
        boundary::in_place(&mut self.windows, |windows| windows.view(host))
    }
}

